// The local admin's generated config (`connect --local`, `npm run dev:local`):
//   config/rendered/wrangler.local.toml  worker/wrangler.toml + the built admin
//                                        UI (admin/dist) as static assets, so
//                                        UI and API share one port and one
//                                        origin (the sign-in cookie just works)
//   worker/.dev.vars                     the keys below; other lines survive
// config/rendered/ and .dev.vars are gitignored.
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { checkEmail } from './login-link.mjs';

export const PUBLISHED_DEV_SECRET = 'dev-only-secret-change-me-0123456789abcdef';
export const DEFAULT_EMAIL = 'admin@example.com';

export const localConfigPath = (root) => join(root, 'config', 'rendered', 'wrangler.local.toml');

/** Pure: product wrangler.toml text → the local one (absolute paths, UI assets). */
export function renderLocalWrangler(base, { root }) {
  const q = (v) => JSON.stringify(v);
  const body = base.replace(/^main\s*=\s*"([^"]+)"\s*$/m, (_, m) => `main = ${q(join(root, 'worker', m))}`);
  if (body === base) throw new Error('worker/wrangler.toml has no `main` line — renderer out of date');
  return [
    '# GENERATED by worker/scripts/lib/local-config.mjs for the local admin. Do not edit.',
    body.trimEnd(),
    '',
    '# The built admin UI on the same port; /api/* always reaches the worker.',
    '[assets]',
    `directory = ${q(join(root, 'admin', 'dist'))}`,
    'not_found_handling = "single-page-application"',
    'run_worker_first = ["/api/*"]',
    '',
  ].join('\n');
}

/** `wrangler dev` argv: secrets and D1 state stay in worker/, where migrate:local and the scripts find them. */
export function wranglerDevArgs({ root, port }) {
  return [
    'dev', '--config', localConfigPath(root),
    '--env-file', join(root, 'worker', '.dev.vars'),
    '--persist-to', join(root, 'worker', '.wrangler', 'state'),
    '--ip', '127.0.0.1', '--port', String(port),
  ];
}

export function parseDevVars(text) {
  const out = {};
  for (const line of text.split('\n')) {
    const m = line.match(/^([A-Za-z_][A-Za-z0-9_]*)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/** The address if checkEmail accepts it (e.g. the git-config one), else ''. */
function usable(raw) {
  try { return raw ? checkEmail(raw) : ''; } catch { return ''; }
}

/**
 * Pure: set the keys a local admin needs in .dev.vars text. The owner's
 * address: `email`, else the one already there, else `fallback` (the git-config
 * address, when it is a usable one), else the product default.
 * The secret is replaced only while it is missing or the published example.
 */
export function updateDevVars(text, { port, email, secret, fallback }) {
  const cur = parseDevVars(text);
  const owner = email ? checkEmail(email) : cur.ADMIN_EMAILS || usable(fallback) || DEFAULT_EMAIL;
  const origin = `http://localhost:${port}`;
  const want = {
    BETTER_AUTH_URL: origin,
    ALLOWED_ORIGINS: `${origin},http://127.0.0.1:${port},http://localhost:5173`,
    OTP_DRY_RUN: '1',
    ADMIN_EMAILS: owner,
  };
  if (!cur.BETTER_AUTH_SECRET || cur.BETTER_AUTH_SECRET === PUBLISHED_DEV_SECRET) want.BETTER_AUTH_SECRET = secret;
  const lines = text.split('\n').filter((l) => {
    const k = l.match(/^([A-Za-z_][A-Za-z0-9_]*)=/)?.[1];
    return !(k && k in want);
  });
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  for (const [k, v] of Object.entries(want)) lines.push(`${k}=${v}`);
  return { text: lines.join('\n') + '\n', email: owner };
}

/** `git config user.email` as seen from the agent repo (its own, else the global one); '' when unset. */
export function gitEmail(repo) {
  try {
    return execFileSync('git', ['-C', repo, 'config', 'user.email'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return '';
  }
}
