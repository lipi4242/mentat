#!/usr/bin/env node
// config/models.json → the next migration in the instance band (900–999),
// end to end — the one command of agent/EXTENDING.md (npm run model):
//
//   npm run model:migration -- <slug>          write, check, apply locally, commit
//   npm run model:migration -- --dry-run       print what it would write
//       [--no-apply]   do not run migrate:local    [--no-commit]   leave it uncommitted
//
// It applies every existing migration to an in-memory SQLite, compares the
// result with config/models.json, and writes only what is missing (new
// tables, new columns) to worker/migrations/09NN_<slug>.sql (mode 0644).
// Nothing missing → writes nothing, exit 0. Then: the models tests, `npm run
// migrate:local` (backup first), and a commit of models.json + the migration
// on the local instance branch (lib/instance-files.mjs), so a git pull or
// reset cannot take the extension away.
import Database from 'better-sqlite3';
import { execFileSync } from 'node:child_process';
import { readFileSync, readdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { modelSql, schemaOf } from '../src/lib/model-sql.mjs';
import { commitInstance, writeInstanceFile } from './lib/instance-files.mjs';

const WORKER = dirname(dirname(fileURLToPath(import.meta.url)));
const MIGRATIONS = join(WORKER, 'migrations');
// MENTAT_MODELS_FILE: `npm run model -- --check` points a --dry-run at a candidate document.
const MODELS = process.env.MENTAT_MODELS_FILE ?? join(WORKER, '..', 'config', 'models.json');
const BAND = [900, 999];

const args = process.argv.slice(2);
const dry = args.includes('--dry-run');
const slug = args.find((a) => !a.startsWith('--'));
if (!dry && !/^[a-z0-9][a-z0-9_]{0,40}$/.test(slug ?? '')) {
  console.error('usage: npm run model:migration -- <slug>   (a-z, 0-9, _), or --dry-run');
  process.exit(2);
}

let models;
try {
  models = JSON.parse(readFileSync(MODELS, 'utf8'));
} catch (e) {
  console.error(`model:migration: cannot read ${MODELS}: ${e.message}`);
  process.exit(2);
}

const files = readdirSync(MIGRATIONS).filter((f) => f.endsWith('.sql')).sort();
const db = new Database(':memory:');
for (const f of files) db.exec(readFileSync(join(MIGRATIONS, f), 'utf8'));
const sql = modelSql(models, schemaOf(db));
if (!sql.length) {
  console.log('model:migration: the schema already matches config/models.json — nothing to write');
  process.exit(0);
}
// Prove the statements run before anyone commits them.
db.exec(sql.join('\n'));

const used = files.map((f) => Number(f.slice(0, 4))).filter((n) => n >= BAND[0] && n <= BAND[1]);
const n = used.length ? Math.max(...used) + 1 : BAND[0];
if (n > BAND[1]) {
  console.error('model:migration: the instance band 0900–0999 is full');
  process.exit(1);
}
const body = `-- Generated by \`npm run model:migration\` from config/models.json.\n-- Instance band 900–999 (the custom plugin); review it before you commit it.\n\n${sql.join('\n')}\n`;
if (dry) {
  process.stdout.write(body);
  process.exit(0);
}
const name = `${String(n).padStart(4, '0')}_${slug}.sql`;
writeInstanceFile(join(MIGRATIONS, name), body);
console.log(`model:migration: wrote worker/migrations/${name}`);

const step = (what, cmd, argv) => {
  try {
    execFileSync(cmd, argv, { cwd: WORKER, stdio: ['ignore', 'ignore', 'inherit'] });
    console.log(`model:migration: ${what} — ok`);
  } catch {
    console.error(`model:migration: ${what} FAILED — nothing committed; fix it, then rerun: ${cmd} ${argv.join(' ')}`);
    process.exit(1);
  }
};
step('models tests', 'npx', ['vitest', 'run', '__tests__/models.test.ts', '__tests__/models-extend.test.ts']);
if (!args.includes('--no-apply')) step('local database migrated (backup first)', 'npm', ['run', 'migrate:local']);
if (!args.includes('--no-commit')) {
  const files = ['config/models.json', `worker/migrations/${name}`];
  const c = commitInstance({ root: join(WORKER, '..'), files, message: `chore(peldany): ${slug} — models.json + ${name}` });
  console.log(c.committed
    ? `model:migration: committed ${c.sha} on local branch ${c.branch} (never push it; update with: git pull origin master)`
    : `model:migration: NOT committed — ${c.reason}`);
}
console.log('model:migration: done. Check: npm run status (migrations), /api/meta lists the change without "pending".');
