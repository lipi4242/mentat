#!/usr/bin/env node
// Instance file → deploy config. The repo holds the PRODUCT; everything that
// belongs to one installation lives in a JSON instance file outside git
// (shape: config/instance.example.json). This script finds it and renders:
//
//   config/rendered/wrangler.toml   worker/wrangler.toml + the instance's
//                                   account, D1 id and [vars]
//   admin/.env.production.local     VITE_INSTANCE_TITLE for the SPA build
//
// Both outputs are gitignored. Usage:
//   node config/instance.mjs render [--out <dir>]   write the files above
//   node config/instance.mjs get <dotted.key>      print one value (e.g. admin.pages_project)
//   node config/instance.mjs path                  print which instance file is used
//
// Lookup order: $MENTAT_ADMIN_INSTANCE, config/instance.json,
// ~/.config/mentat-admin/instance.json. No file → exit 1 with a hint.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const CONFIG_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(CONFIG_DIR);
const WORKER_DIR = join(ROOT, 'worker');

function fail(msg) {
  console.error(`instance: ${msg}`);
  process.exit(1);
}

function instancePath() {
  // An explicit path is a promise: if it is wrong, say so rather than quietly
  // falling through to some other instance file on this machine.
  const explicit = process.env.MENTAT_ADMIN_INSTANCE;
  if (explicit) {
    if (!existsSync(explicit)) fail(`MENTAT_ADMIN_INSTANCE points at a missing file: ${explicit}`);
    return explicit;
  }
  const candidates = [
    join(CONFIG_DIR, 'instance.json'),
    join(homedir(), '.config', 'mentat-admin', 'instance.json'),
  ];
  const found = candidates.find((p) => existsSync(p));
  if (!found) {
    fail(`no instance file. Looked at:\n  ${candidates.join('\n  ')}\n` +
      'Copy config/instance.example.json to one of these and fill it in.');
  }
  return found;
}

function get(obj, key) {
  return key.split('.').reduce((o, k) => (o == null ? undefined : o[k]), obj);
}

const REQUIRED = [
  'title',
  'cloudflare.account_id',
  'worker.database_id',
  'worker.vars.ALLOWED_ORIGINS',
  'worker.vars.ADMIN_EMAILS',
  'worker.vars.OTP_SENDER',
  'admin.pages_project',
];

function loadInstance() {
  const path = instancePath();
  let inst;
  try {
    inst = JSON.parse(readFileSync(path, 'utf8'));
  } catch (e) {
    fail(`${path}: not valid JSON (${e.message})`);
  }
  const missing = REQUIRED.filter((k) => {
    const v = get(inst, k);
    return typeof v !== 'string' || !v.trim();
  });
  if (missing.length) fail(`${path}: missing or empty: ${missing.join(', ')}`);
  return inst;
}

// A JSON string is a valid TOML basic string for everything we write here.
const q = (v) => JSON.stringify(String(v));

/** Pure: product wrangler.toml text + instance → deploy wrangler.toml text.
 *  `toWorker` is the relative path from the output dir back to worker/. */
export function renderWrangler(base, inst, toWorker) {
  const vars = { INSTANCE_TITLE: inst.title, ...inst.worker.vars };
  const lines = base.split('\n');
  const out = [
    '# GENERATED by config/instance.mjs from worker/wrangler.toml + the instance',
    '# file. Do not edit, do not commit (config/rendered/ is gitignored).',
  ];
  const seen = new Set();
  let section = '';
  for (const line of lines) {
    const header = line.match(/^\s*\[\[?([^\]]+)\]\]?\s*$/);
    if (header) {
      section = header[1].trim();
      out.push(line);
      if (section === 'vars') {
        for (const [k, v] of Object.entries(vars)) out.push(`${k} = ${q(v)}`);
      }
      continue;
    }
    if (section === 'vars') {
      // The whole [vars] section is the instance's; the product's local-dev
      // values are dropped. Comments survive.
      if (/^\s*[A-Za-z_][A-Za-z0-9_]*\s*=/.test(line)) continue;
      out.push(line);
      continue;
    }
    const kv = line.match(/^(\s*)([a-z_]+)\s*=\s*(.*)$/);
    if (!kv) {
      out.push(line);
      continue;
    }
    const [, indent, key] = kv;
    if (section === '' && key === 'name') {
      out.push(`${indent}name = ${q(inst.worker.name || 'mentat-admin-api')}`);
      out.push(`${indent}account_id = ${q(inst.cloudflare.account_id)}`);
      seen.add('name');
    } else if (section === '' && key === 'main') {
      const main = JSON.parse(kv[3]);
      out.push(`${indent}main = ${q(join(toWorker, main))}`);
      seen.add('main');
    } else if (section === 'd1_databases' && key === 'database_name') {
      out.push(`${indent}database_name = ${q(inst.worker.database_name || 'mentat-admin-db')}`);
      seen.add('database_name');
    } else if (section === 'd1_databases' && key === 'database_id') {
      out.push(`${indent}database_id = ${q(inst.worker.database_id)}`);
      out.push(`${indent}migrations_dir = ${q(join(toWorker, 'migrations'))}`);
      seen.add('database_id');
    } else {
      out.push(line);
    }
  }
  for (const k of ['name', 'main', 'database_name', 'database_id']) {
    if (!seen.has(k)) throw new Error(`worker/wrangler.toml has no \`${k}\` line — renderer out of date`);
  }
  if (!out.some((l) => /^\s*\[vars\]\s*$/.test(l))) throw new Error('worker/wrangler.toml has no [vars] section');
  return out.join('\n');
}

function render(outDir) {
  const inst = loadInstance();
  const base = readFileSync(join(WORKER_DIR, 'wrangler.toml'), 'utf8');
  const wranglerDir = outDir ?? join(CONFIG_DIR, 'rendered');
  const toWorker = relative(wranglerDir, WORKER_DIR);
  mkdirSync(wranglerDir, { recursive: true });
  writeFileSync(join(wranglerDir, 'wrangler.toml'), renderWrangler(base, inst, toWorker));
  const envFile = outDir ? join(outDir, '.env.production.local') : join(ROOT, 'admin', '.env.production.local');
  writeFileSync(envFile, `# GENERATED by config/instance.mjs — do not commit.\nVITE_INSTANCE_TITLE=${q(inst.title)}\n`);
  console.error(`instance: rendered ${relative(ROOT, join(wranglerDir, 'wrangler.toml'))} and ${relative(ROOT, envFile)}`);
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const [cmd, arg, arg2] = process.argv.slice(2);
  if (cmd === 'render') render(arg === '--out' ? arg2 : undefined);
  else if (cmd === 'get') {
    const v = arg ? get(loadInstance(), arg) : undefined;
    if (typeof v !== 'string') fail(`no string value at "${arg}"`);
    process.stdout.write(v);
  } else if (cmd === 'path') process.stdout.write(instancePath());
  else fail('usage: node config/instance.mjs render [--out <dir>] | get <dotted.key> | path');
}
